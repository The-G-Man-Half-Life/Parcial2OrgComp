// LOOP PRINCIPAL: sondeo continuo del teclado
// ============================================================
(WAIT_PRESS)
    @KBD
    D=M
    @WAIT_PRESS
    D;JEQ

    @KBD
    D=M
    @77
    D=D-A
    @CHECK_M
