// ============================================================
// Calcula el desplazamiento del puesto segun count (0,1,2) y
// salta a la rutina DRAW_X guardada en letterTarget.
// ============================================================
(COMPUTE_OFFSET_AND_JUMP)
    @count
    D=M
    @IS_COUNT_0
    D;JEQ
    @count
    D=M
    @1
    D=D-A
    @IS_COUNT_1
    D;JEQ
    @IS_COUNT_2
    0;JMP

(IS_COUNT_0)
    @0
    D=A
    @slotOffset
    M=D
    @letterTarget
    A=M
    0;JMP

