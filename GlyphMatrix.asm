    @WAIT_RELEASE
    0;JMP

// Si count ya es 3, esta tecla es la '4ta letra': libera memoria.
// Si hay espacio, guarda a donde saltar (DRAW_M) y calcula el puesto.
(CHECK_M)
    @count
    D=M
    @3
    D=D-A
    @RESET
    D;JEQ
    @DRAW_M
    D=A
    @letterTarget
    M=D
    @COMPUTE_OFFSET_AND_JUMP
    0;JMP

