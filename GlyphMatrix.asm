// ============================================================
// Calcula el desplazamiento del puesto segun count (0,1,2) y
// salta a la rutina DRAW_X guardada en letterTarget (salto indirecto:
// A=M carga la direccion de ROM guardada, 0;JMP salta ahi).
// ============================================================
